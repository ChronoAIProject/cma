macro_rules! entry {
    ($collection:literal, $($erasure:expr => $indexed:expr),+ $(,)?) => {
        Entry {
            collection: $collection,
            rules: &[$(Rule { erasure: $erasure, indexed: $indexed }),+],
        }
    };
}


//! Add an empty Workspace and Agent to an existing owned Sandbox.
use super::*;
use layer2_core::sandbox::Sandbox;

impl InlineAgentLifecycle {
    pub(super) async fn contextual_sandbox(
        &self,
        caller: &Caller,
        actor: Option<&layer2_core::resource_access::ResourceActor>,
        request: &AgentLifecycleCreateRequest,
    ) -> Result<Sandbox, AgentLifecycleProvisioningError> {
        let id = request.sandbox_id.as_ref().ok_or_else(|| {
            AgentLifecycleProvisioningError::Invalid("sandbox_id is required".into())
        })?;
        let sandbox = self
            .workspaces
            .authorize_lifecycle_sandbox(caller, actor, &SandboxId(id.clone()))
            .await
            .map_err(|error| sandbox_context_error(error, id))?;
        workspace::validate_scopes(request, &sandbox.credential.effective_reaches())?;
        Ok(sandbox)
    }

    pub(super) async fn prepare_existing_sandbox(
        &self,
        caller: &Caller,
        input: &mut ProvisionInput,
    ) -> Result<(), AgentLifecycleProvisioningError> {
        let sandbox = self
            .contextual_sandbox(caller, input.actor.as_ref(), &input.request)
            .await?;
        if input
            .existing_sandbox_id
            .as_deref()
            .is_some_and(|id| id != sandbox.id.as_str())
        {
            return Err(AgentLifecycleProvisioningError::Conflict(
                "the recorded Sandbox does not match this request".into(),
            ));
        }
        self.operations
            .mark_sandbox(&input.lease, sandbox.id.as_str())
            .await
            .map_err(|_| AgentLifecycleProvisioningError::Unavailable)?;
        // The operation id is generated by the store, not the display name or URL.
        let name = format!("agent-{}", input.lease.id);
        let content = WorkspaceProfileContent {
            location: layer2_core::profiles::WorkspaceLocation::Directory { name: name.clone() },
            name,
            setup_commands: Vec::new(),
            agent_profiles: Vec::new(),
        };
        let revision = self
            .profiles
            .create_workspace_for_owner(
                &caller.subject,
                &format!("agent-manager:{}:workspace", input.key),
                format!("{} workspace", input.request.name),
                "Empty Agent workspace".into(),
                content,
            )
            .await
            .map_err(validation::profile_error)?;
        let workspace = self
            .workspaces
            .create_for_lifecycle(
                caller,
                input.actor.as_ref(),
                &sandbox.id,
                &WorkspaceProfileRef::new(revision.profile_id, revision.revision),
                &input.lease.id,
            )
            .await
            .map_err(|error| sandbox_context_error(error, sandbox.id.as_str()))?;
        self.operations
            .append_event(
                &input.lease,
                1,
                "sandbox_ready",
                "running",
                "Preparing an empty workspace in the selected Sandbox",
            )
            .await
            .map_err(|_| AgentLifecycleProvisioningError::Unavailable)?;
        tokio::time::timeout(Duration::from_secs(180), async {
            loop {
                let current = self
                    .workspaces
                    .read(caller, &workspace.id)
                    .await
                    .map_err(workspace_error)?;
                match current.status {
                    WorkspaceStatus::Ready => return Ok(()),
                    WorkspaceStatus::Preparing => {
                        tokio::time::sleep(Duration::from_millis(500)).await
                    }
                    _ => {
                        return Err(AgentLifecycleProvisioningError::Conflict(
                            "empty workspace preparation failed".into(),
                        ))
                    }
                }
            }
        })
        .await
        .map_err(|_| AgentLifecycleProvisioningError::Unavailable)??;
        input.request.workspace_id = Some(workspace.id.to_string());
        input.request.sandbox_id = None;
        input.existing_sandbox_id = Some(sandbox.id.to_string());
        Ok(())
    }
}

fn sandbox_context_error(
    error: layer2_core::sandbox::WorkspaceServiceError,
    id: &str,
) -> AgentLifecycleProvisioningError {
    match error {
        layer2_core::sandbox::WorkspaceServiceError::Connection(error) => {
            validation::connection_error(error, json!({"type":"sandbox", "id":id}))
        }
        error => workspace_error(error),
    }
}

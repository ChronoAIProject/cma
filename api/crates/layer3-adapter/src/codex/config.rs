//! The configuration file this kernel reads before it starts.
//!
//! Its own kernel's, so it lives in its own kernel's directory. This was in the
//! supervisor, rendered there in this vocabulary at this path — which worked
//! while there was one kernel and wrote a file the other two do not read into
//! every one of their pods once there were three.
//!
//! The supervisor still writes it. What it no longer does is compose it: it is
//! handed a path and a body, writes them, and reads neither.
//!
//! ## No credential is in here
//!
//! The agent is pointed at the supervisor's loopback proxy and given a
//! placeholder. Everything that makes the call authentic is added by that
//! proxy, so the kernel never holds a credential and never needs restarting
//! when one changes.

use crate::hosted::PLACEHOLDER_CREDENTIAL;
use crate::{RuntimePermission, RuntimeSpec};

/// Where the file goes, relative to the pod's home.
pub(super) const CONFIG_PATH: &str = ".codex/config.toml";

/// Configuration for a session spending its owner's own account.
///
/// The difference that matters is an absence: no provider is declared, so the
/// kernel uses its own built-in one and the credential it signed itself in
/// with. Naming our proxy here instead would have the owner sign in and then
/// never spend the account they signed into — the session would run on the
/// platform's credential while its owner believed otherwise, which is the
/// exact failure `CredentialMode::Own` exists to prevent.
///
/// The permission settings are the same in both shapes. Whose account pays
/// says nothing about what the agent may do unattended.
fn render_own_account(spec: &RuntimeSpec, model: &str) -> String {
    format!(
        r#"# Generated by CMA. Do not edit by hand.
#
# This session runs on its owner's own account with the model vendor. The agent
# signs itself in inside this sandbox and keeps the result here; no credential
# of theirs reaches the service that started it, and none appears in this file
# or in the environment.
model = "{model}"
model_reasoning_effort = "{effort}"

# What the agent may do unattended. The sandbox around this process is the
# outer boundary and is not affected by these; they govern what the agent does
# inside it.
approval_policy = "{approval}"
{legacy_sandbox}
{trigger_profile}
"#,
        effort = spec
            .options
            .reasoning_effort
            .clone()
            .unwrap_or_else(|| "medium".to_string()),
        approval = approval_policy(spec),
        legacy_sandbox = legacy_sandbox_setting(spec),
        trigger_profile = trigger_permission_profile(spec),
    )
}

/// The name the agent reads its placeholder credential from.
///
/// This kernel's configuration names an environment variable rather than
/// carrying a value, and the supervisor's pty path sets the same name.
const PLACEHOLDER_VAR: &str = "CHRONO_UPSTREAM_PLACEHOLDER_KEY";

/// Render this kernel's configuration for a session.
///
/// Two shapes, and which one a session gets is decided by whose account pays
/// for it. A session on the platform's credential is pointed at the loopback
/// proxy, which attaches it; a session on its owner's own account is pointed
/// at nothing and signs itself in, which is the only arrangement under which
/// the owner's credential never has to exist outside their sandbox.
pub(super) fn render(
    spec: &RuntimeSpec,
    proxy_base_url: &str,
    model: &str,
    wire_api: &str,
) -> String {
    if spec.options.own_credential {
        return render_own_account(spec, model);
    }
    format!(
        r#"# Generated by CMA. Do not edit by hand.
#
# The agent talks to a proxy on loopback inside its own sandbox. That proxy
# attaches the owner's credential, so no credential appears here, in the
# environment, or anywhere else the agent can read.
model = "{model}"
model_provider = "chrono"
model_reasoning_effort = "{effort}"

# What the agent may do unattended. The sandbox around this process is the
# outer boundary and is not affected by these; they govern what the agent does
# inside it.
approval_policy = "{approval}"
{legacy_sandbox}
{trigger_profile}

[model_providers.chrono]
name = "Chrono LLM"
base_url = "{base_url}"
env_key = "{PLACEHOLDER_VAR}"
wire_api = "{wire_api}"
"#,
        base_url = proxy_base_url.trim_end_matches('/'),
        effort = spec
            .options
            .reasoning_effort
            .clone()
            .unwrap_or_else(|| "medium".to_string()),
        approval = approval_policy(spec),
        legacy_sandbox = legacy_sandbox_setting(spec),
        trigger_profile = trigger_permission_profile(spec),
    )
}

fn approval_policy(spec: &RuntimeSpec) -> &'static str {
    if spec.runtime_policy_required {
        return "never";
    }
    match spec.options.permission {
        RuntimePermission::Guarded => "on-request",
        RuntimePermission::Autonomous => "on-failure",
        RuntimePermission::Unrestricted => "never",
    }
}

fn legacy_sandbox_setting(spec: &RuntimeSpec) -> String {
    if spec.runtime_policy_required {
        // Permission profiles and legacy sandbox settings do not compose.
        // Any sandbox_mode in the loaded config disables default_permissions.
        return String::new();
    }
    let mode = match spec.options.permission {
        RuntimePermission::Guarded => "read-only",
        RuntimePermission::Autonomous => "workspace-write",
        RuntimePermission::Unrestricted => "danger-full-access",
    };
    format!("sandbox_mode = \"{mode}\"")
}

/// Trigger sessions need unattended command execution, but their network is
/// a managed loopback path rather than general provider egress. The runtime's
/// signed policy remains authoritative for the service, numeric repository,
/// ref, and operation after the request reaches that local gateway.
fn trigger_permission_profile(spec: &RuntimeSpec) -> &'static str {
    if !spec.runtime_policy_required {
        return "";
    }
    r#"default_permissions = "cma-trigger"

[features]
network_proxy = true

[permissions.cma-trigger]
extends = ":workspace"

[permissions.cma-trigger.network]
enabled = true
enable_socks5 = false
enable_socks5_udp = false
allow_upstream_proxy = false
allow_local_binding = false

[permissions.cma-trigger.network.domains]
"127.0.0.2" = "allow"
"#
}

/// The inert credential the agent presents to the loopback proxy.
///
/// Named here because the configuration above points at it, and shared with
/// the rest of the environment so the two cannot disagree.
pub(super) fn placeholder() -> (String, String) {
    (
        PLACEHOLDER_VAR.to_string(),
        PLACEHOLDER_CREDENTIAL.to_string(),
    )
}


//! Writing the agent kernel's configuration before it starts.
//!
//! The kernel is pointed at the supervisor's local proxy rather than at the
//! real model endpoint, and given a placeholder key. Everything that makes the
//! call authentic is added by the proxy, so the kernel never holds a
//! credential and never needs restarting when one changes.

use std::path::{Path, PathBuf};

/// Placeholder the kernel presents to the local proxy.
///
/// The proxy replaces it outright. It exists only because the kernel refuses to
/// start without some key being present.
pub const PLACEHOLDER_KEY: &str = "local-proxy-no-credential-needed";

/// How the kernel should be configured.
#[derive(Debug, Clone)]
pub struct AgentConfig {
    /// Base URL of the supervisor's local proxy.
    pub proxy_base_url: String,
    /// Model to select.
    pub model: String,
    /// Which request shape the upstream speaks.
    pub wire_api: String,
    /// Display name for the provider entry.
    pub provider_name: String,
    /// How much deliberation to ask of the model.
    pub effort: String,
    /// When the agent must stop and ask before acting.
    pub approval_policy: String,
    /// How far the agent may reach inside its sandbox.
    pub sandbox_mode: String,
}

impl AgentConfig {
    /// Render the kernel's configuration file.
    pub fn render(&self) -> String {
        format!(
            r#"# Generated by the chrono-bot runtime supervisor. Do not edit by hand.
#
# The agent talks to a proxy on loopback inside its own sandbox. That proxy
# attaches the owner's credential, so no credential appears here, in the
# environment, or anywhere else the agent can read.
model = "{model}"
model_provider = "chrono"
model_reasoning_effort = "{effort}"

# What the agent may do unattended. The sandbox around this process is the
# outer boundary and is not affected by these; they govern what the agent does
# inside it.
approval_policy = "{approval_policy}"
sandbox_mode = "{sandbox_mode}"

[model_providers.chrono]
name = "{provider_name}"
base_url = "{base_url}"
env_key = "CHRONO_UPSTREAM_PLACEHOLDER_KEY"
wire_api = "{wire_api}"
"#,
            model = self.model,
            provider_name = self.provider_name,
            base_url = self.proxy_base_url.trim_end_matches('/'),
            wire_api = self.wire_api,
            effort = self.effort,
            approval_policy = self.approval_policy,
            sandbox_mode = self.sandbox_mode,
        )
    }

    /// Where the configuration belongs, given a home directory.
    pub fn path_in(home: &Path) -> PathBuf {
        home.join(".codex").join("config.toml")
    }

    /// Write the configuration, creating the directory if needed.
    pub fn write(&self, home: &Path) -> std::io::Result<PathBuf> {
        let path = Self::path_in(home);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(&path, self.render())?;
        tracing::info!(path = %path.display(), base_url = %self.proxy_base_url, "agent configuration written");
        Ok(path)
    }
}

#[cfg(test)]
mod tests {
    /// A configuration with the cautious defaults.
    fn sample() -> AgentConfig {
        AgentConfig {
            proxy_base_url: "http://127.0.0.1:9091".into(),
            model: "gpt-5.6-sol".into(),
            wire_api: "responses".into(),
            provider_name: "Chrono LLM".into(),
            effort: "medium".into(),
            approval_policy: "on-request".into(),
            sandbox_mode: "read-only".into(),
        }
    }

    use super::*;

    fn config() -> AgentConfig {
        AgentConfig {
            proxy_base_url: "http://127.0.0.1:9091/v1".into(),
            model: "gpt-5.6-sol".into(),
            effort: "medium".into(),
            approval_policy: "on-request".into(),
            sandbox_mode: "read-only".into(),
            wire_api: "responses".into(),
            provider_name: "Chrono LLM".into(),
        }
    }

    #[test]
    fn the_rendered_config_points_at_the_local_proxy() {
        let rendered = config().render();
        assert!(
            rendered.contains(r#"base_url = "http://127.0.0.1:9091/v1""#),
            "{rendered}"
        );
        assert!(rendered.contains(r#"model_provider = "chrono""#));
        assert!(rendered.contains(r#"wire_api = "responses""#));
    }

    #[test]
    fn no_credential_appears_in_the_rendered_config() {
        // The whole point: the file the agent reads must be inert.
        let rendered = config().render();
        for forbidden in ["Bearer", "sk-", "token", "secret"] {
            assert!(
                !rendered.contains(forbidden),
                "config leaked {forbidden}: {rendered}"
            );
        }
    }

    #[test]
    fn the_base_url_carries_no_version_segment() {
        // The brokered upstream's own base URL already ends in a version, and
        // the broker appends whatever path arrives. A version here produces
        // .../v1/v1/responses upstream and a 404 the agent reports as a model
        // failure. Regression guard for exactly that.
        let mut c = config();
        c.proxy_base_url = "http://127.0.0.1:9091".into();
        let rendered = c.render();
        assert!(
            rendered.contains(r#"base_url = "http://127.0.0.1:9091""#),
            "{rendered}"
        );
        assert!(
            !rendered.contains("9091/v1"),
            "the agent base_url must not carry a version segment: {rendered}"
        );
    }

    #[test]
    fn a_trailing_slash_on_the_proxy_url_is_normalised() {
        let mut c = config();
        c.proxy_base_url = "http://127.0.0.1:9091/v1/".into();
        assert!(c
            .render()
            .contains(r#"base_url = "http://127.0.0.1:9091/v1""#));
    }

    #[test]
    fn the_config_lands_where_the_kernel_looks_for_it() {
        let p = AgentConfig::path_in(Path::new("/home/chrono"));
        assert_eq!(p, Path::new("/home/chrono/.codex/config.toml"));
    }

    #[test]
    fn writing_creates_the_directory_and_the_file() {
        let dir = std::env::temp_dir().join(format!("chrono-agent-cfg-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let written = config().write(&dir).expect("writes");
        assert!(written.exists());
        let body = std::fs::read_to_string(&written).expect("readable");
        assert!(body.contains("model_provider"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn the_rendered_config_states_the_permission_settings() {
        // These decide what the agent may do unattended, so they must appear
        // in the file rather than being left to the kernel's own defaults.
        let rendered = AgentConfig {
            effort: "xhigh".into(),
            approval_policy: "never".into(),
            sandbox_mode: "danger-full-access".into(),
            ..sample()
        }
        .render();
        assert!(
            rendered.contains(r#"model_reasoning_effort = "xhigh""#),
            "{rendered}"
        );
        assert!(
            rendered.contains(r#"approval_policy = "never""#),
            "{rendered}"
        );
        assert!(
            rendered.contains(r#"sandbox_mode = "danger-full-access""#),
            "{rendered}"
        );
    }

    #[test]
    fn a_guarded_session_renders_the_cautious_settings() {
        let rendered = sample().render();
        assert!(
            rendered.contains(r#"approval_policy = "on-request""#),
            "{rendered}"
        );
        assert!(
            rendered.contains(r#"sandbox_mode = "read-only""#),
            "{rendered}"
        );
    }
}
